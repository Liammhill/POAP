import { applyStarling, defaultRule, groupTxns, parseStarling, ruleKey, sampleStarlingCsv } from './starling.ts';
import { sampleVault } from './sample.ts';
const ok = (c: boolean, m: string) => { if (!c) { console.error('FAIL', m); (globalThis as any).process.exit(1); } console.log('ok', m); };
const grid = sampleStarlingCsv().split('\n').map((l) => l.slice(1, -1).split('","'));
const txns = parseStarling(grid);
ok(txns.length === 12, 'parses 12 rows');
const v = sampleVault();
const groups = groupTxns(txns);
const choice = Object.fromEntries(groups.map((g) => [ruleKey(g.dir, g.name), defaultRule(g, v)]));
const k = (d: 'in' | 'out', n: string) => choice[ruleKey(d, n)];
ok(k('in', 'RIVERSIDE HOUSING TRUS').kind === 'client', 'truncated name matches existing client');
ok(k('in', 'GREENWAY FOUNDATION').kind === 'new', 'unknown payer becomes new client');
ok(k('in', 'STARLING BANK').kind === 'ignore', 'interest ignored');
ok(k('out', 'E HERZOG').kind === 'ignore', 'own transfer ignored');
ok(k('out', 'HMRC SELF ASSESSMENT').kind === 'ignore', 'tax payment ignored');
ok((k('out', 'ADOBE SYSTEMS') as any).category === 'Software & subscriptions', 'adobe categorised');
const r = applyStarling(v, groups, choice);
ok(r.income + r.reconciled === 4 && r.expenses === 5 && r.newClients === 1, `counts ${JSON.stringify({ ...r, vault: 0 })}`);
const again = applyStarling(r.vault, groupTxns(txns), Object.fromEntries(groupTxns(txns).map((g) => [ruleKey(g.dir, g.name), defaultRule(g, r.vault)])));
ok(again.income + again.reconciled + again.expenses + again.newClients === 0, 're-import adds nothing');
console.log('all starling tests passed');
